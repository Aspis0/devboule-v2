describe("a file dropped on the composer", () => {
  it("shows a pill with its name, type and size", async () => {
    const { container } = await renderDesign(createHost());

    await dispatchTransferEvent(composer(container), "drop", {
      files: [imageFile("hero.png", PNG_BYTES, "image/png")],
    });

    expect(pillNames(container)).toEqual(["hero.png"]);
    const pill = container.querySelector(".design-attachment-pill");
    expect(pill?.querySelector(".design-attachment-kind")?.textContent).toBe("PNG");
    expect(pill?.querySelector(".design-attachment-size")?.textContent).toBe(
      formatAttachmentSize(PNG_BYTES.length),
    );
  });

  it("marks the composer while a file is over it and clears the mark on drop", async () => {
    const { container } = await renderDesign(createHost());
    const target = composer(container);

    await dispatchTransferEvent(target, "dragenter", {
      files: [imageFile("hero.png", PNG_BYTES, "image/png")],
    });
    expect(target.getAttribute("data-drop-active")).toBe("true");

    await dispatchTransferEvent(target, "drop", {
      files: [imageFile("hero.png", PNG_BYTES, "image/png")],
    });
    expect(target.hasAttribute("data-drop-active")).toBe(false);
  });

  it("cancels the drop so the window does not navigate to the file", async () => {
    const { container } = await renderDesign(createHost());

    const event = await dispatchTransferEvent(composer(container), "drop", {
      files: [imageFile("hero.png", PNG_BYTES, "image/png")],
    });

    expect(event.defaultPrevented).toBe(true);
  });

  it("ignores a drag that carries no file", async () => {
    const { container } = await renderDesign(createHost());
    const target = composer(container);

    const over = await dispatchTransferEvent(target, "dragover", { types: ["text/plain"] });
    await dispatchTransferEvent(target, "drop", { types: ["text/plain"] });

    expect(over.defaultPrevented).toBe(false);
    expect(target.hasAttribute("data-drop-active")).toBe(false);
    expect(container.querySelector(".design-attachment-pill")).toBeNull();
  });

  it("says so when the drop yielded no file at all, as a folder does", async () => {
    const { container } = await renderDesign(createHost());

    await dispatchTransferEvent(composer(container), "drop", {
      files: [],
      items: [{ kind: "file", getAsFile: () => null }],
    });

    expect(feedback(container)).toEqual([
      "One dropped item was not a file, so nothing was attached from it. A folder cannot be attached; drop the image files themselves.",
    ]);
  });

  it("reports the folder in a drop that also carried an image", async () => {
    const { container } = await renderDesign(createHost());

    await dispatchTransferEvent(composer(container), "drop", {
      files: [],
      items: [
        { kind: "file", getAsFile: () => imageFile("hero.png", PNG_BYTES, "image/png") },
        { kind: "file", getAsFile: () => null },
      ],
    });

    // The image is attached and the folder is still accounted for.
    expect(pillNames(container)).toEqual(["hero.png"]);
    expect(feedback(container)).toEqual([
      "One dropped item was not a file, so nothing was attached from it. A folder cannot be attached; drop the image files themselves.",
    ]);
  });
});


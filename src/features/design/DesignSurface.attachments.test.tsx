/**
 * happy-dom's DataTransfer is a stub, so the payload is a plain object hung off the
 * event. React reads `dataTransfer` off the native event, which is exactly what the
 * component's handlers do too, so the path under test is the real one.
 */
async function dispatchTransferEvent(
  target: Element,
  type: "dragenter" | "dragover" | "dragleave" | "drop" | "paste",
  dataTransfer: unknown,
): Promise<Event> {
  const event = new Event(type, { bubbles: true, cancelable: true });
  Object.defineProperty(event, "dataTransfer", { value: dataTransfer });
  Object.defineProperty(event, "clipboardData", { value: dataTransfer });
  await act(async () => {
    target.dispatchEvent(event);
    await Promise.resolve();
    await Promise.resolve();
    await Promise.resolve();
  });
  return event;
}

function pillNames(container: HTMLDivElement): string[] {
  return Array.from(container.querySelectorAll(".design-attachment-name")).map(
    (element) => element.textContent ?? "",
  );
}

function feedback(container: HTMLDivElement): readonly string[] {
  return Array.from(container.querySelectorAll(".design-attachment-feedback p")).map(
    (element) => element.textContent ?? "",
  );
}

function notice(container: HTMLDivElement): HTMLElement | null {
  return container.querySelector<HTMLElement>(".design-attachment-notice");
}

async function fillDraft(container: HTMLDivElement, prompt: string): Promise<void> {
  const setValue = Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, "value")?.set;
  if (setValue === undefined) throw new Error("textarea value setter did not exist");
  await act(async () => {
    setValue.call(draftField(container), prompt);
    draftField(container).dispatchEvent(new Event("input", { bubbles: true }));
  });
}

